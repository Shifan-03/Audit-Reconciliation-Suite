export function getFinancialStatementsForEntityAndPeriod(
  entityId: string,
  period: 'Q4_2026' | 'Q3_2026' | 'FY_2025' | 'TTM_2026'
): FinancialStatementsData {
  // Base weights by entity
  let multiplier = 1.0;
  if (entityId === 'ENT-NA') multiplier = 0.55;
  else if (entityId === 'ENT-EMEA') multiplier = 0.22;
  else if (entityId === 'ENT-APAC') multiplier = 0.13;
  else if (entityId === 'ENT-BD') multiplier = 0.10;
  else multiplier = 1.0; // Consolidated

  // Period multiplier
  let pMult = 1.0;
  let periodLabel = 'For the Ten Months Ended October 31, 2026';
  let asOfLabel = 'October 31, 2026';

  if (period === 'Q3_2026') {
    pMult = 0.75;
    periodLabel = 'For the Nine Months Ended September 30, 2026';
    asOfLabel = 'September 30, 2026';
  } else if (period === 'FY_2025') {
    pMult = 0.82;
    periodLabel = 'For the Full Year Ended December 31, 2025 (Audited)';
    asOfLabel = 'December 31, 2025';
  } else if (period === 'TTM_2026') {
    pMult = 1.20;
    periodLabel = 'Trailing Twelve Months (TTM) Ended October 31, 2026';
    asOfLabel = 'October 31, 2026';
  }

  const factor = multiplier * pMult;

  // Scale line items accurately
  const mapItem = (item: any) => ({
    ...item,
    currentPeriod: Math.round(item.currentPeriod * factor),
    priorPeriod: Math.round(item.priorPeriod * factor),
    entityBreakdown: {
      'ENT-NA': Math.round(item.currentPeriod * 0.55 * pMult),
      'ENT-EMEA': Math.round(item.currentPeriod * 0.22 * pMult),
      'ENT-APAC': Math.round(item.currentPeriod * 0.13 * pMult),
      'ENT-BD': Math.round(item.currentPeriod * 0.10 * pMult),
      'ELIMINATIONS': item.accountCode.startsWith('12') || item.accountCode.startsWith('20')
        ? -Math.round(item.currentPeriod * 0.05 * pMult)
        : 0,
    },
  });

  const assets = FINANCIAL_STATEMENTS_DATA.balanceSheet.assets.map(mapItem);
  const liabilities = FINANCIAL_STATEMENTS_DATA.balanceSheet.liabilities.map(mapItem);
  const equity = FINANCIAL_STATEMENTS_DATA.balanceSheet.equity.map(mapItem);

  const totalAssets = assets.reduce((sum, a) => sum + a.currentPeriod, 0);
  const totalLiab = liabilities.reduce((sum, l) => sum + l.currentPeriod, 0);
  const totalEq = totalAssets - totalLiab; // Balance sheet identity always holds

  // Adjust last equity line so it balances perfectly to the dollar
  if (equity.length > 0) {
    const eqSumExceptLast = equity.slice(0, -1).reduce((s, e) => s + e.currentPeriod, 0);
    equity[equity.length - 1].currentPeriod = totalEq - eqSumExceptLast;
  }

  const revenue = FINANCIAL_STATEMENTS_DATA.incomeStatement.revenue.map(mapItem);
  const cogs = FINANCIAL_STATEMENTS_DATA.incomeStatement.costOfGoodsSold.map(mapItem);
  const opex = FINANCIAL_STATEMENTS_DATA.incomeStatement.operatingExpenses.map(mapItem);
  const taxes = FINANCIAL_STATEMENTS_DATA.incomeStatement.taxesAndInterest.map(mapItem);

  const totRev = revenue.reduce((s, r) => s + r.currentPeriod, 0);
  const totCogs = cogs.reduce((s, c) => s + c.currentPeriod, 0);
  const grossProfit = totRev - totCogs;
  const totOpex = opex.reduce((s, o) => s + o.currentPeriod, 0);
  const operatingIncome = grossProfit - totOpex;
  const totTaxInt = taxes.reduce((s, t) => s + t.currentPeriod, 0);
  const netIncome = operatingIncome + totTaxInt;

  return {
    balanceSheet: {
      asOfDate: asOfLabel,
      totalAssets,
      totalLiabilitiesAndEquity: totalAssets,
      assets,
      liabilities,
      equity,
    },
    incomeStatement: {
      period: periodLabel,
      revenue,
      costOfGoodsSold: cogs,
      grossProfit,
      operatingExpenses: opex,
      operatingIncome,
      taxesAndInterest: taxes,
      netIncome,
    },
    cashFlow: {
      period: periodLabel,
      operatingActivities: FINANCIAL_STATEMENTS_DATA.cashFlow.operatingActivities.map(mapItem),
      investingActivities: FINANCIAL_STATEMENTS_DATA.cashFlow.investingActivities.map(mapItem),
      financingActivities: FINANCIAL_STATEMENTS_DATA.cashFlow.financingActivities.map(mapItem),
      netCashChange: Math.round(FINANCIAL_STATEMENTS_DATA.cashFlow.netCashChange * factor),
      beginningCash: Math.round(FINANCIAL_STATEMENTS_DATA.cashFlow.beginningCash * factor),
      endingCash: Math.round(FINANCIAL_STATEMENTS_DATA.cashFlow.endingCash * factor),
    },
    equityChanges: {
      shareCapitalBeginning: Math.round(FINANCIAL_STATEMENTS_DATA.equityChanges.shareCapitalBeginning * factor),
      shareCapitalAdditions: 0,
      shareCapitalEnding: Math.round(FINANCIAL_STATEMENTS_DATA.equityChanges.shareCapitalEnding * factor),
      retainedEarningsBeginning: Math.round(FINANCIAL_STATEMENTS_DATA.equityChanges.retainedEarningsBeginning * factor),
      netIncomeAddition: netIncome,
      dividendDistributions: -Math.round(Math.abs(FINANCIAL_STATEMENTS_DATA.equityChanges.dividendDistributions) * factor),
      retainedEarningsEnding: Math.round(FINANCIAL_STATEMENTS_DATA.equityChanges.retainedEarningsEnding * factor),
      otherReserves: Math.round(FINANCIAL_STATEMENTS_DATA.equityChanges.otherReserves * factor),
      totalEquityEnding: totalEq,
    },
  };
}

